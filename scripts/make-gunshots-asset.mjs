#!/usr/bin/env node
/* ===========================================================================
   make-gunshots-asset.mjs -- pack assets/gunshots/*.mp3 into nz-gunshots-asset.js

   nz-audio.js (section 15c) plays real recordings for the pistol, the rifle
   and the pump shotgun. It does not fetch the MP3s one by one: it injects
   nz-gunshots-asset.js once, after the page's 'load' event, and decodes the
   clips from the base64 inside it. One file, one request, works from any
   static host and from file://, and the build already knows how to ship it.

       node scripts/make-gunshots-asset.mjs

   Clip names are <set>_<n>.mp3. Every set below must have at least one clip.
   To swap a sound: replace the MP3 (mono, already trimmed to the onset and
   loudness-matched to its siblings - see scripts/gunshots-prep.py) and re-run.
   ======================================================================== */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const DIR = path.join(ROOT, "assets", "gunshots");
const OUT = path.join(ROOT, "nz-gunshots-asset.js");
const SETS = ["pistol_near", "pistol_far", "rifle_near", "rifle_far",
              "shotgun_near", "shotgun_far", "pump_back", "pump_fwd"];

const files = (await readdir(DIR)).filter((f) => f.endsWith(".mp3"))
  .sort((a, b) => a.localeCompare(b, "en", { numeric: true }));
const clips = {};
let bytes = 0;
for (const f of files) {
  const m = /^(.*)_(\d+)\.mp3$/.exec(f);
  if (!m || !SETS.includes(m[1])) { console.warn(`gunshots: skipping ${f} (not <set>_<n>.mp3)`); continue; }
  const buf = await readFile(path.join(DIR, f));
  bytes += buf.length;
  (clips[m[1]] ||= []).push(buf.toString("base64"));
}
const missing = SETS.filter((s) => !clips[s]);
if (missing.length) { console.error(`gunshots: no clips for ${missing.join(", ")}`); process.exit(1); }

const head =
`/* ===========================================================================
   NZ-GUNSHOTS-ASSET -- recorded gunfire for nz-audio.js (section 15c).
   GENERATED by scripts/make-gunshots-asset.mjs from assets/gunshots/*.mp3.
   Do not edit by hand.

   Walther PPQ 9x19, AR-15 5.56x45, Benelli Nova 12 ga, Winchester Model 12
   pump action. From The Free Firearm Sound Library by Still North Media
   (Ben Jaszczak, Brian Nelson, Kevin Heras, Matthew Nanney), released under
   CC0 1.0 - no rights reserved. See assets/gunshots/README.md.

   Not loaded by a <script> tag: nz-audio.js requests this file itself once
   the page has finished loading, decodes the clips, then deletes
   window.NZ_GUNSHOTS so the text does not stay in memory.
   ======================================================================== */
`;
const body = "window.NZ_GUNSHOTS = {\n  v: 1,\n  clips: {\n" +
  SETS.map((s) => `    ${s}: [\n${clips[s].map((b) => `      "${b}"`).join(",\n")}\n    ]`).join(",\n") +
  "\n  }\n};\n";
await writeFile(OUT, head + body);
const n = SETS.reduce((a, s) => a + clips[s].length, 0);
console.log(`gunshots: ${n} clips, ${(bytes / 1024).toFixed(0)} KB of MP3 -> ` +
  `nz-gunshots-asset.js (${((head.length + body.length) / 1024).toFixed(0)} KB)`);
